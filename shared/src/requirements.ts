function toRequirement(seed: ReqSeed, assignmentId: string): Requirement {
  return {
    id: seed.id,
    assignmentId,
    originalText: seed.original,
    displayText: seed.display,
    category: seed.cat,
    required: seed.required ?? true,
    expectedBehavior: seed.expected,
    testMethod: seed.method,
    evidenceNeeded: seed.evidence,
    maxScoreContribution: seed.weight,
    verificationStatus: seed.ambiguous ? "ambiguous" : "planned",
    instructorNotes: seed.notes,
    weight: seed.weight,
    criterionKey: seed.criterion,
  };
}

const SEED_MAP: Record<string, ReqSeed[]> = {
  COMMON: COMMON_SEEDS,
  A1: A1_SEEDS,
  A2: A2_SEEDS,
  A3: A3_SEEDS,
  A4: A4_SEEDS,
  A5: A5_SEEDS,
  A6: A6_SEEDS,
};

export const REQUIREMENTS: Requirement[] = Object.entries(SEED_MAP).flatMap(([aid, seeds]) =>
  seeds.map((s) => toRequirement(s, aid)),
);

/** Таңдалған тапсырма үшін тексерілетін талаптар: ортақ + жеке. */
export function requirementsForAssignment(assignmentId: string): Requirement[] {
  return REQUIREMENTS.filter((r) => r.assignmentId === "COMMON" || r.assignmentId === assignmentId);
}

export function getAssignment(id: string): Assignment | undefined {
  return ASSIGNMENTS.find((a) => a.id === id);
}
